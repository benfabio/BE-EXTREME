### quantile mapping (QM) strategies. Re-use Script#7.1.2 used to compute scPDSI

### The Standardized Precipitation–Evapotranspiration Index (SPEI) is a climate drought index that quantifies anomalies
### in climatic water balance, defined as: D = P - PET
### SPEI measures how unusually dry or wet conditions are relative to the local historical climate,
### accounting for both water supply and atmospheric demand.

### SPEI is constructed (conceptually) through:
# - Climatic water balance through monthly (or aggregated) precipitation is combined with estimated PET to compute 𝑃−𝑃𝐸𝑇
# - Accumulation over a chosen timescale: The water balance is accumulated over a user-defined window 
# (e.g. 1, 3, 6, 12 months), allowing SPEI to represent drought processes operating at different temporal scales.
# - Standardization: The accumulated series is fitted to a probability distribution (commonly log-logistic) and
# transformed into standardized units (mean = 0, SD = 1).
# - Interpretation: 
#Interpretation guidelines
#   SPEI value      Interpretation
#   0	            Normal
#   −1	            Moderate drought
#   −1.5	        Severe drought
#   −2 or lower	    Extreme drought
#   +1	            Moderately wet
#   +2	            Extremely wet

### -> Because it is standardized, SPEI values are comparable across regions and climates.

### What SPEI is not good at:
# - Does not represent actual soil moisture
# - Does not directly measure plant water status
# - Is not an observation, but a climate-derived indicator

### What is scPDSI NOT good for:
# - Not good for short-term droughts: Poor sensitivity to: Flash droughts, agricultural drought at weekly scales,
# too much “memory”
# - Not good for impact-specific questions as it does not directly represent: Root-zone soil moisture, crop stress,
# Ecosystem functioning, Vegetation response may lag or decouple
# - Fixed soil parameters; Soil water capacity is simplified, often poorly constrained, and no dynamic rooting depth or land cover change
# - Not event-based so cannot clearly isolate: Onset timing, Termination timing & poor for attribution of single drought events

### Avoid scPDSI if:
# - You care about weekly–monthly agricultural impacts
# - You want explicit timescale control
# - You are modeling ecosystem or crop responses
# - You need process realism in evapotranspiration
# - You want to link drought to plant traits, biomass, or resistance metrics! 

### In short: use scPDSI to describe background climatic dryness; use SPI/SPEI to describe event timing and scale
### -> We need to estimate SPEI based on the our long-term climate reconstructions and compare them 

### R script to: 
###  - Load the TS of daily total precipitation and daily maximum temperature generated by different quantiles 
