### Add identifier with a scale-agnostic, reusable solution that:
# - Keeps event IDs separate
# - Preserves severity classes
# - Is safe for EP-level time series

# For testing FUN:
# df = spei
# spei_var = "SPEI3"
# scale_label = "SPEI3"

identify_spei_events <- function(df, spei_var, scale_label) {
  
    #' @param df: data frame containing SPEI time series
    #' @param spei_var: name of the SPEI column (character string, e.g. "SPEI3")
    #' @param scale_label: label used to tag event IDs (e.g. "SPEI3", "SPEI6")
    #' @return df: modified 'df' with the event IDs
    
    # Arrange to make sure EP x time ordering is adequate
    df <- df %>% arrange(EP,m) %>% group_by(EP) %>%
        mutate(
            spei_value = .data[[spei_var]], # Extract the selected SPEI variable in a generic way (.data[[...]] allows non-standard evaluation safely)
            spei_class = case_when(
                spei_value > 2            ~ "Extremely wet",
                spei_value > 1.5          ~ "Severely wet",
                spei_value > 1            ~ "Moderately wet",
                spei_value > 0.5          ~ "Mildly wet",
                spei_value >= -0.5 & spei_value <= 0.5 ~ "Normal",
                spei_value < -0.5 & spei_value >= -1   ~ "Mild drought",
                spei_value < -1   & spei_value >= -1.5 ~ "Moderate drought",
                spei_value < -1.5 & spei_value >= -2   ~ "Severe drought",
                spei_value < -2             ~ "Extreme drought",
                TRUE                        ~ NA_character_
            ), # Classify SPEI values into wet / normal / drought severity classes
            spei_event_type = case_when(
                spei_value < -0.5 ~ "drought",
                spei_value >  0.5 ~ "wet",
                TRUE              ~ "normal"
            ), # Reduce classes to a simple event type
            event_break = spei_event_type != lag(
                spei_event_type,
                default = first(spei_event_type)
            ),
            # Identify breaks between consecutive time steps
            # Assign a raw event ID by cumulatively summing breaks 
            event_id_raw = cumsum(event_break)
        ) %>%
        ungroup() %>%
        # Assign final drought & wet events identifiers
        mutate(
            event_id = case_when(
                spei_event_type == "drought" ~ paste0(EP, "_", scale_label, "_D_", event_id_raw),
                spei_event_type == "wet" ~ paste0(EP, "_", scale_label, "_W_", event_id_raw),
                spei_event_type == "normal" ~ "Normal"
            )
        ) # eo mutate
    
    # Return 
    df # str(df); data.frame(df[10000:10200,])

} # eo FUN - identify_spei_events

# Apply FUN to spei
