compute_SPEI <- function(system, region, method, min_age = 10) {

        #' This function takes four arguments and returns a formatted data.frame:
        #' @param system System name (character): 'grasslands' or 'forests'
        #' @param region Region name (character): 'SCH' or 'HND' or 'SWA'
        #' @param method Which quantile mapping approach to run (character): 'global' or 'monthly' or 'mw' or 'anomalies'
        #' @param min_age Age below which forets data should not be taken into account because StandAge is outside of GAMM
        #' traning range (10-40 years old) (integer) - Default == 10 because youngest stands fit into the GAMMs are 12 yo
        #' @return A formatted data.frame combining the DSM data
        
        ## Message
        message(paste("\nComputing SPEI for the ",system," of the ",region," based on the ",method," QM strategy\n", sep = ""))
        if( system == "forests" ) {
            setwd("/home/fbenedetti/ERA5-Land-DEU-processed/daily/quantile_mapping_outputs/combined_time_series_full/forests")
        } else {
            setwd("/home/fbenedetti/ERA5-Land-DEU-processed/daily/quantile_mapping_outputs/combined_time_series_full/grasslands")
        } # eo if else loop - directories

        ## Loading daily Ta_200 & total precip.
        if( system == "forests" ) {
            setwd("/home/fbenedetti/ERA5-Land-DEU-processed/daily/quantile_mapping_outputs/combined_time_series_full/forests")
            d_temp <- readRDS(paste("table_combined_obs+corr_max_Ta_200_",system,"_",region,".rds", sep = ""))
            d_precip <- get(load(paste("table_combined_obs+corr_",method,"_total_precipitation_",system,"_",region,".Rdata", sep = "")))
        } else {
            d_temp <- get(load(paste("table_combined_obs+corr_",method,"_max_Ta_200_",system,"_",region,".Rdata", sep = "")))
            d_precip <- get(load(paste("table_combined_obs+corr_",method,"_total_precipitation_",system,"_",region,".Rdata", sep = "")))
        } # eo if else loop - directories

        ## In a mclappy, compute DSL at EP-level
        require("parallel")
        
        list_SPEI <- mclapply(X = unique(d_temp$EP),
        
            FUN = function(p) {
                # For testing:
                # p <- unique(d_temp$EP)[13]; p

                # Subset EP
                message(paste("Computing SPEI for ",p,sep = ""))
                sub_d_temp <- d_temp[d_temp$EP == p,]
                sub_d_precip <- d_precip[d_precip$EP == p,]

                # Add D/M/Y based on 'Date'
                sub_d_temp$DOY <- lubridate::yday(sub_d_temp$Date)
                sub_d_temp$month <- lubridate::month(sub_d_temp$Date)
                sub_d_temp$year <- lubridate::year(sub_d_temp$Date)

                # Adjust colnames before merging
                if( system == "grasslands" ) {
                    colnames(sub_d_temp)[5] <- "temperature"
                } else {
                    colnames(sub_d_temp)[6] <- "temperature"
                }
                # For precip. too
                colnames(sub_d_precip)[5] <- "precipitation"
                
                # Merge
                sub_d_temp <- sub_d_temp %>% left_join(sub_d_precip %>% select(EP, Date, precipitation), by = c("EP","Date"))
                # summary(sub_d_temp) # OK

                ### 09/07/26: Add a minimum age requirement for forests based on 'min_age' argument
                ### -> Discard values for stands that show a stand age < min_age 
                if( system == "forests" ) {
                    if( sum(unique(sub_d_temp$Stand_age) < min_age ) > 0 ) {
                        sub_d_temp <- sub_d_temp[sub_d_temp$Stand_age >= min_age ,]
                    } # eo if else loop - min_age
                } # eo if else loop - forests

                # Need to aggregate to the monthly scale as SPEI operates on monthly time step
                sub_d_temp$m <- floor_date(sub_d_temp$Date, "month") # summary(sub_d_temp$m)

                d_mon <- sub_d_temp %>%
                    group_by(m) %>%
                    summarize(
                        precip = sum(precipitation, na.rm = TRUE),
                        temp = mean(temperature, na.rm = TRUE)
                    ) # eo summarize
                # summary(data.frame(d_mon))

                # Pick latitude value based on 'region'
                if(region == "SCH") {
                    lat <- 53
                } else if(region == "HND") {
                    lat <- 51.15
                } else if(region == "SWA") {
                    lat <- 48.45
                } # eo if else loop - region

                # Compute PE using the Thornthwaite equation ('SPEI' package)
                d_mon$PE <- SPEI::thornthwaite(Tave = d_mon$temp, lat = lat)
                # Compute climatic water balance (WB = P − PET)
                d_mon$WB <- (d_mon$precip) - (d_mon$PE)
                # summary(d_mon)

                ### Compute SPEI at different time scales: 3/6/12 months
                # SPEI-3 (short-term stress / resistance)
                spei_3 <- spei(d_mon$WB, scale = 3)
                # SPEI-6 (seasonal biomass response)
                spei_6 <- spei(d_mon$WB, scale = 6)
                # SPEI-12 (legacy effects / recovery)
                spei_12 <- spei(d_mon$WB, scale = 12)
                
                # Add SPEI values to 'd_mon' as different columns
                d_mon$SPEI3 <- spei_3$fitted
                d_mon$SPEI6 <- spei_6$fitted
                d_mon$SPEI12 <- spei_12$fitted
                # summary(d_mon)

                # Add EP ID
                d_mon <- d_mon %>% add_column(EP = p, .before = 1)

                # Clean and return
                rm(spei_3,spei_6,spei_12,sub_d_temp,sub_d_precip)
                gc()
                
                return(d_mon)

            } # eo FUN - EPs
            ,
            mc.cores = 20

        ) # eo mclapply - list_SPEI

        ## Rbind
        t_SPEI <- dplyr::bind_rows(list_SPEI)
        # dim(t_SPEI) ; summary(t_SPEI) ; head(data.frame(t_SPEI))
        rm(list_SPEI); gc()
        
        ## Add metadata
        t_SPEI <- t_SPEI %>% add_column(region = region, .before = 3)
        t_SPEI <- t_SPEI %>% add_column(qm_method = method, .before = 4)
        t_SPEI <- t_SPEI %>% add_column(System = system, .before = 1)

        ## And save in proper dir
        if( exists("t_SPEI") == FALSE ) {
            stop(
              paste("!!! ERROR: Could not find the final SPEI table for the ",system," of the ",region," based on the ",method," QM strategy\n", sep = "")
            )
        } else {
            setwd(extremes_dir)
            paste("Saving the SPEI table for the ",system," of the ",region," based on the ",method," QM strategy\n", sep = "")
            save(x = t_SPEI, file = paste("table_SPEI_",system,"_",region,"_",method,".Rdata", sep = "") )
        } # eo if else loop

} # eo FUN - compute_SPEI

### Apply compute_scPDSI() to all regions and based on all bias correction stategies

### 09/07/26: Re-computing monthly SPEI over the full reconstruction period for the forests using a min_age cap of 10 yo

