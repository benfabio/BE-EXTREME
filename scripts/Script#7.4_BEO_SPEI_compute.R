identify_pdsi_events <- function(df) {
  
    #' @param df: data frame containing SPEI time series
    #' @return df: modified 'df' with the event IDs

    df <- df %>% arrange(EP,Date) %>% 
        group_by(EP) %>%
        mutate(
            pdsi_value = Value,
            pdsi_class = case_when(
                pdsi_value > 4 ~ "Extremely wet",
                pdsi_value >= 3 & pdsi_value <= 4 ~ "Severely wet",
                pdsi_value >= 2 & pdsi_value <  3 ~ "Moderately wet",
                pdsi_value >= 1 & pdsi_value <  2 ~ "Mildly wet",
                pdsi_value > -1 & pdsi_value <  1 ~ "Normal",
                pdsi_value <= -1 & pdsi_value > -2 ~ "Mild drought",
                pdsi_value <= -2 & pdsi_value > -3 ~ "Moderate drought",
                pdsi_value <= -3 & pdsi_value > -4 ~ "Severe drought",
                pdsi_value <= -4 ~ "Extreme drought",
                TRUE ~ NA_character_
            ),
            
            pdsi_event_type = case_when(
                pdsi_value <= -1 ~ "drought",
                pdsi_value >=  1 ~ "wet",
                TRUE ~ "normal"
            ),
      
            event_break  = pdsi_event_type != lag(pdsi_event_type,
                default = first(pdsi_event_type)
            ),
            
            event_id_raw = cumsum(event_break)
        ) %>%
        ungroup() %>%
        mutate(
            event_id = case_when(
                pdsi_event_type == "drought" ~
                paste0(EP, "_scPDSI_D_", event_id_raw),
                pdsi_event_type == "wet" ~
                paste0(EP, "_scPDSI_W_", event_id_raw),
                TRUE ~ "Normal"
            )
        ) # eo mutate

        # Return
        df

} # eo identify_pdsi_events

