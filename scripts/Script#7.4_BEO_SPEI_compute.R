### KEY TAKE AWAY: based on scPDSI, drought events are much MUCH longer than based on SPEI !! This is a 
### critical observation and it makes sense. scPDSI index is for identifying persistent regimes over very long scales.
### Meanwhile, the SPEI is meant for short to medium-term events and is better at evaluating the onset and termination
### of the events.

### By design, once scPDSI enters drought regime (< -1), it tends to stay there until sustained wet anomalies occur. 
### Meanwhile, SPEI has no "memory" as it just a standard anomaly based on accumulation windows (3/6/12 months). 
### A scPDSI drought lasting >100 months means: “The system never fully returned to a normal hydroclimatic balance for ~8+ years.”
### This is likely why studies do not use scPDSI to identify discrete drought events. 

# ✅ sc️ scPDSI is good for:
# Long-term drought background state
# Multi-year to decadal hydrological stress
# Legacy effects
# Groundwater / baseflow context
# Comparing climatic regimes

# ❌ scPDSI is NOT good for:
# Event-based resistance / recovery metrics
# Onset timing
# Short-term ecosystem responses
# Counting independent droughts

### -> Use SPEI 3/6/12
### SPEI6 is usually preferred over SPEI12 for drought event detection because it best balances responsiveness and persistence.
# Scale	    What it represents	                                    Memory
# SPEI 3	Short-term anomalies (meteorological / soil moisture)	Low
# SPEI 6	Seasonal to inter-seasonal drought stress	            Medium
# SPEI 12   Annual water balance	                                High

# SPEI 3: Captures short, sharp events; splits long droughts into multiple fragments; very sensitive to monthly variability; "sees monthly shocks"
# SPEI 6: Smooths short-term noise; events match ecosystem responses; widely used for ecological & hydrological drought events
# SPEI 12: Highly smoothed; merges consecutive short events; produces fewer but much longer events; behaves almost like scPDSI


